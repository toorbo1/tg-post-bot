def generate_post_content(topic):
    template = random.choice(POST_TEMPLATES)
    safe_tag = "".join(e for e in topic.lower() if e.isalnum())[:15] or "пост"
    title = template["title"].format(topic=topic)
    intro = template["intro"].format(topic=topic)
    body = "\n\n".join(template["body"])
    cta = template["cta"]
    tags = template["tags"].format(safe_tag=safe_tag)
    credit = random.choice(BOT_CREDITS)
    return f"<b>{title}</b>\n\n{intro}\n\n{body}\n\n{cta}\n\n{tags}{credit}"

@bot.callback_query_handler(func=lambda call: True)
def handle_callbacks(call):
    chat_id = call.message.chat.id

    if call.data == "delete_post":
        try:
            bot.delete_message(chat_id, call.message.message_id)
        except:
            pass
        bot.answer_callback_query(call.id, "Пост удалён")
        return

    msg = call.message
    caption = msg.caption or msg.text or ""
    topic = "VPN"

    if call.data == "change_img":
        bot.answer_callback_query(call.id, "🔍 Ищу новую картинку...")
        new_img = search_image(topic + " " + str(random.randint(1, 99)))
        try:
            bot.edit_message_media(
                chat_id=chat_id, message_id=msg.message_id,
                media=types.InputMediaPhoto(media=new_img, caption=caption, parse_mode="HTML"),
                reply_markup=get_post_inline_keyboard(chat_id)
            )
        except:
            bot.send_message(chat_id, f"Новая картинка: {new_img}")

    elif call.data == "regen_text":
        bot.answer_callback_query(call.id, "🔄 Перегенерирую текст...")
        if "VPN" in caption or "Наш ВПН" in caption or "VPN" in caption:
            new_text = generate_vpn_post()
        else:
            new_text, _ = generate_auto_post()
        try:
            if msg.photo:
                bot.edit_message_caption(
                    chat_id=chat_id, message_id=msg.message_id,
                    caption=new_text, parse_mode="HTML",
                    reply_markup=get_post_inline_keyboard(chat_id)
                )
            else:
                bot.edit_message_text(
                    chat_id=chat_id, message_id=msg.message_id,
                    text=new_text, parse_mode="HTML",
                    reply_markup=get_post_inline_keyboard(chat_id)
                )
        except Exception as e:
            logger.error(f"Edit error: {e}")

    elif call.data == "edit_text":
        bot.answer_callback_query(call.id, "✏️ Введите новый текст поста")
        awaiting_edit[chat_id] = {
            "message_id": msg.message_id,
            "has_photo": bool(msg.photo)
        }
        bot.send_message(
            chat_id,
            "✏️ <b>Отправьте новый текст для этого поста:</b>\n\n"
            "<i>Вы можете написать свой вариант или скопировать текст из любого источника.</i>"
        )

    elif call.data == "publish_channel":
        channel = config.get("channel")
        if not channel:
            bot.answer_callback_query(call.id, "❌ Канал не настроен!", show_alert=True)
            bot.send_message(chat_id, "Настройте канал через  Настроить канал")
            return
        bot.answer_callback_query(call.id, "📤 Публикую...")
        try:
            if msg.photo:
                bot.send_photo(channel, photo=msg.photo[-1].file_id, caption=caption, parse_mode="HTML")
            else:
                bot.send_message(channel, caption, parse_mode="HTML")
            bot.send_message(chat_id, f"✅ Пост опубликован в {channel}!")
        except Exception as e:
            bot.send_message(chat_id, f"❌ Ошибка: {e}")

