def search_image(query):
    """Ищет уникальное изображение без повторов"""
    global used_images

    if not query:
        query = "technology"

    # Сначала пробуем сгенерировать пиксельную картинку
    pixel_art = generate_pixel_art_image(query)
    if pixel_art:
        return pixel_art

    # Если не получилось - ищем через DuckDuckGo
    # Сохраняем файл с историей изображений
    history_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "used_images.json")
    try:
        with open(history_file, "r") as f:
            saved_used = json.load(f)
        used_images.extend(saved_used)
        used_images = list(set(used_images))  # убираем дубликаты
    except:
        pass

    variations = [
        f"{query} unique photo",
        f"{query} original image",
        f"{query} real photo",
        f"{query} authentic",
        f"{query} modern",
        f"{query} abstract",
        query
    ]

    for attempt in range(5):
        try:
            variation = random.choice(variations)
            # Добавляем случайность для уникальности запроса
            rand_suffix = random.randint(1, 999999)
            q = f"{variation} {rand_suffix}"

            time.sleep(random.uniform(0.3, 1.0))

            with DDGS() as ddgs:
                results = list(ddgs.images(q, max_results=10))
                random.shuffle(results)

                for r in results:
                    url = r.get('image') or r.get('thumbnail')
                    if url and url.startswith('http') and not url.endswith('.svg') and 'placeholder' not in url:
                        # Проверяем по полному списку использованных
                        if url not in used_images:
                            used_images.append(url)
                            # Ограничиваем память
                            if len(used_images) > 200:
                                used_images = used_images[-100:]
                            # Сохраняем в файл
                            try:
                                with open(history_file, "w") as f:
                                    json.dump(used_images[-100:], f)
                            except:
                                pass
                            return url

        except Exception as e:
            logger.warning(f"Image search attempt {attempt+1}: {e}")
            time.sleep(0.5)

    # Если не нашли новое — берём из резервного пула
    available = list(range(len(IT_IMAGES)))
    if used_images:
        available = [i for i in available if IT_IMAGES[i] not in used_images]
    if not available:
        used_images = []
        available = list(range(len(IT_IMAGES)))

    idx = random.choice(available)
    img = IT_IMAGES[idx]
    used_images.append(img)

    # Разные параметры для вариативности
    params = [
        f"?w={random.choice([1200, 1400, 1600, 1800])}&q={random.randint(80, 95)}",
        f"?auto=format&fit=crop&w={random.choice([1200, 1400, 1600])}&h={random.choice([800, 900, 1000, 1100])}",
    ]
    return img + random.choice(params)

