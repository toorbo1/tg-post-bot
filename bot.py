def schedule_next_posts():
    global scheduler_timer, daily_schedule
    posts_count = config.get("posts_per_day", 4)
    if not config.get("auto_posting", True):
        logger.info("Auto-posting is disabled")
        scheduler_timer = threading.Timer(3600, schedule_next_posts)
        scheduler_timer.daemon = True
        scheduler_timer.start()
        return

    now = datetime.datetime.now()

    # Если расписание на сегодня уже есть и посты ещё остались — не пересоздаём
    if daily_schedule:
        remaining = [s for s in daily_schedule if s["time"] > now]
        if remaining:
            logger.info(f"Schedule already exists, {len(remaining)} posts remaining")
            return

    # Все посты на сегодня опубликованы — ждём следующего дня
    if daily_schedule and all(s["time"] <= now for s in daily_schedule):
        midnight = (now + datetime.timedelta(days=1)).replace(hour=0, minute=0, second=5, microsecond=0)
        wait = (midnight - now).total_seconds()
        logger.info(f"All posts published for today. Next schedule at {midnight.strftime('%H:%M %d.%m.%Y')}")
        daily_schedule = []
        scheduler_timer = threading.Timer(wait, schedule_next_posts)
        scheduler_timer.daemon = True
        scheduler_timer.start()
        return

    custom_times = config.get("post_times", [])
    CATEGORY_NAMES = {
        "facts": "Факты", "tech_news": "IT-новости",
        "security_tip": "Кибербезопасность", "internet_tip": "✨Лайфхаки",
        "vpn_tip": "🔒VPN-советы", "funny": "😂Юмор"
    }

    deliveries = []
    for i in range(posts_count):
        cat = random.choice(POST_CATEGORIES)
        if custom_times and i < len(custom_times):
            try:
                parts = custom_times[i].strip().split(":")
                h, m = int(parts[0]), int(parts[1])
                post_time = now.replace(hour=h, minute=m, second=0, microsecond=0)
            except:
                post_time = None
            if post_time and post_time <= now:
                post_time = None
        else:
            post_time = None

        if post_time is None:
            now_rand = datetime.datetime.now()
            today_end = now_rand.replace(hour=23, minute=59, second=59, microsecond=0)
            seconds_left = max(1, int((today_end - now_rand).total_seconds()))
            used = [d["delay"] for d in deliveries if "delay" in d]
            for _ in range(50):
                delay = random.randint(300, seconds_left)
                if abs(delay - sum(used)) > 600:
                    break
            post_time = now_rand + datetime.timedelta(seconds=delay)
            deliveries.append({"time": post_time, "category": cat, "index": i, "delay": delay})
        else:
            delay = int((post_time - now).total_seconds())
            deliveries.append({"time": post_time, "category": cat, "index": i, "delay": max(1, delay)})

    if not deliveries:
        midnight = (now + datetime.timedelta(days=1)).replace(hour=0, minute=0, second=5, microsecond=0)
        wait = (midnight - now).total_seconds()
        scheduler_timer = threading.Timer(wait, schedule_next_posts)
        scheduler_timer.daemon = True
        scheduler_timer.start()
        return

    deliveries.sort(key=lambda x: x["time"])
    daily_schedule = deliveries

    schedule_text = (
        f"📋 <b>Расписание автопостинга на {now.strftime('%d.%m.%Y')}</b>\n"
        f" Канал: {config.get('channel')}\n"
        f"📝 Всего постов: {len(deliveries)}\n"
    )
    if custom_times:
        times_str = ", ".join(custom_times[:posts_count])
        schedule_text += f"⏰ Заданное время: {times_str}\n"
    schedule_text += "\n"
    for item in deliveries:
        cat_name = CATEGORY_NAMES.get(item["category"], "📌 Пост")
        schedule_text += f"⏰ {item['time'].strftime('%H:%M')}  —  {cat_name}\n"

    logger.info(f"Scheduled {len(deliveries)} auto-posts")

    def post_at(index):
        if index >= len(deliveries):
            midnight = (datetime.datetime.now() + datetime.timedelta(days=1)).replace(hour=0, minute=0, second=5, microsecond=0)
            wait = (midnight - datetime.datetime.now()).total_seconds()
            logger.info(f"All {len(deliveries)} posts done. Next day schedule in {wait:.0f}s")
            daily_schedule.clear()
            scheduler_timer = threading.Timer(wait, schedule_next_posts)
            scheduler_timer.daemon = True
            scheduler_timer.start()
            return
        item = deliveries[index]
        timer = threading.Timer(item["delay"], perform_auto_post, args=(item["index"],))
        timer.daemon = True
        timer.start()

    post_at(0)

    if admin_chat_id:
        try:
            bot.send_message(admin_chat_id, schedule_text)
        except Exception as e:
            logger.warning(f"Could not send schedule to admin: {e}")

def perform_auto_post(index):
    result = generate_auto_post()
    if len(result) == 3:
        text, category, has_photo = result
    else:
        text, category = result
        has_photo = True

    image_topic = CATEGORY_IMAGES.get(category, "IT technology")
    publish_to_channel(text, image_topic, has_photo)

    global daily_schedule
    daily_schedule = [s for s in daily_schedule if s.get("index") != index]
    delays = [0]
    posts_count = config.get("posts_per_day", 4)
    now = datetime.datetime.now()
    today_end = now.replace(hour=23, minute=59, second=59, microsecond=0)
    seconds_left = (today_end - now).total_seconds()
    if seconds_left <= 0 or index + 1 >= posts_count:
        schedule_next_posts()
        return
    intervals = sorted([random.random() for _ in range(posts_count)])
    scaled = [int(seconds_left * i / sum(intervals)) for i in intervals]
    delays = [scaled[0]] + [scaled[i] - scaled[i-1] for i in range(1, posts_count)]
    if index + 1 < len(delays):
        next_delay = delays[index + 1]
    else:
        next_delay = max(1, seconds_left // (posts_count - index))
    timer = threading.Timer(next_delay, perform_auto_post, args=(index + 1,))
    timer.daemon = True
    timer.start()

