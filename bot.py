@bot.message_handler(commands=['set_times'])
def cmd_set_times(message):
    global admin_chat_id, daily_schedule
    admin_chat_id = message.chat.id
    parts = message.text.split(maxsplit=1)
    if len(parts) < 2:
        bot.send_message(
            message.chat.id,
            "❌ Использование: <code>/set_times 09:00, 14:00, 19:00, 22:00</code>\n"
            "Укажите время через запятую. Количество часов = количество постов в день."
        )
        return
    raw = parts[1].strip()
    times = [t.strip() for t in raw.replace("，", ",").split(",") if t.strip()]
    validated = []
    for t in times:
        try:
            h, m = t.split(":")
            h, m = int(h), int(m)
            if 0 <= h <= 23 and 0 <= m <= 59:
                validated.append(f"{h:02d}:{m:02d}")
            else:
                raise ValueError
        except:
            bot.send_message(message.chat.id, f"❌ Неверный формат времени: <code>{t}</code>. Используйте ЧЧ:ММ")
            return
    posts_count = config.get("posts_per_day", 4)
    if len(validated) != posts_count:
        bot.send_message(
            message.chat.id,
            f"❌ Нужно указать ровно <b>{posts_count}</b> времени (по числу постов в день).\n"
            f"Сейчас указано: <b>{len(validated)}</b>.\n"
            f"Измените количество постов: /set_posts {len(validated)}"
        )
        return
    config["post_times"] = validated
    save_config()
    daily_schedule = []
    bot.send_message(message.chat.id, f"✅ Время публикаций установлено: <b>{', '.join(validated)}</b>")
    if config.get("auto_posting", True):
        schedule_next_posts()

